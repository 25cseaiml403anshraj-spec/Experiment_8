import numpy as np

a = np.array([10, 20, 30, 40, 50])

print("Array:")
print(a)

print("First element:", a[0])
print("Third element:", a[2])
print("Last element:", a[-1])

print("First three elements:", a[0:3])
print("Elements from index 2 to 4:", a[2:5])
print("Every second element:", a[::2])

